import { transportBoundaryOptions } from "./transport-boundary.js";

/**
 * Правило no-restricted-syntax: запрет прямых HTTP-вызовов путей модуля `users`
 * вне единственной транспортной границы (`src/shared/api/users`).
 *
 * Причина та же, что у reports: модуль переведён на операции сгенерированного
 * контракта, и адрес там связан с методом, телом и типом ответа.
 *
 * Отличие в форме адреса, и форм этих две — ровно потому, что префикс модуля
 * (`/api/users`) добавляет интерсептор инстанса, а не call-site:
 *
 *   * полный путь `/api/users/v1/...` — интерсептор пропускает его как есть;
 *   * путь без префикса `/v1/workspaces/...` и легаси-форма `/v1/users/...` —
 *     интерсептор дописывает префикс сам, то есть такой вызов доезжает до
 *     бекенда ровно так же.
 *
 * Правило обязано ловить обе: гейт, который краснеет только на первой, оставляет
 * обход границы зелёным (замечание архитектурного ревью PR #46). Пути других
 * модулей под шаблон не попадают: `/v2/reports`, `/v1/reports/search` и
 * `/v1/user-settings/...` начинаются иначе.
 *
 * Краснота правила закреплена тестом
 * `src/shared/api/users/transportBoundary.gate.test.ts`.
 */

const message =
  "Путь модуля users вызывается напрямую. Транспорт этого модуля живёт в src/shared/api/users (операции сгенерированного контракта) — добавьте или используйте операцию там.";

export const noDirectUsersTransportOptions = transportBoundaryOptions(
  "^\\/(api\\/users\\/v[0-9]|v[0-9]+\\/(workspaces|users)(\\/|$))",
  message
);
